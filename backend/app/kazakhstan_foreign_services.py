def build_kazakhstan_foreigner_service_answer(
    user_message: str,
    language: LanguageCode,
    registry: SourceRegistry,
    *,
    context_text: str = "",
) -> tuple[GroundedAnswerDraft, list[Citation], dict[str, str | None]] | None:
    """Answer a recognized foreigner service question from its official snapshot."""
    from backend.app.kazakhstan_consular_documents import (
        build_kazakhstan_consular_document_answer,
    )

    document_answer = build_kazakhstan_consular_document_answer(
        user_message,
        language,
        registry,
        context_text=context_text,
    )
    if document_answer is not None:
        return document_answer

    lang = language.value if language.value in _COPY else "en"
    combined = _normalize(f"{context_text}\n{user_message}")
    intent = _detect_intent(combined)
    if intent is None:
        return None

    source_ids = _source_ids_for_intent(intent)
    sources = [registry.get_source_by_id(source_id) for source_id in source_ids]
    if any(
        source is None
        or source.source_type.value != "official"
        or not is_retrievable_source(source)
        for source in sources
    ):
        return None
    selected = [source for source in sources if source is not None]
    copy = _COPY[lang]
    direct = copy[intent]
    source_by_key = {
        key: registry.get_source_by_id(source_id) for key, source_id in _SOURCES.items()
    }
    fact_sections: list[GroundedAnswerSection] = []
    citations: list[Citation] = []
    for index, (fact_key, source_key) in enumerate(_FACT_SOURCES[intent], start=1):
        source = source_by_key[source_key]
        if source is None:
            return None
        claim = _FACT_COPY[lang][fact_key]
        fact_sections.append(
            GroundedAnswerSection(
                heading=copy["facts"],
                body=claim,
                source_ids=[source.source_id],
            )
        )
        citations.append(
            Citation(
                citation_id=f"KZ-FOREIGNER-{index}",
                source_id=source.source_id,
                claim=claim,
                supporting_quote=source.content,
                confidence=0.96,
            )
        )
    step_key = (
        "step_iin"
        if intent == "iin"
        else "step_bank"
        if intent == "bank"
        else ("step_visa" if intent in {"tourism", "treatment", "private"} else "step_consular")
    )
    steps = [
        GroundedAnswerSection(
            heading=copy["steps"],
            body=copy[step_key],
        )
    ]
    draft = GroundedAnswerDraft(
        scenario=UserScenario.kazakhstan_entry.value,
        risk_level=RiskLevel.legal_sensitive.value,
        language=lang,
        direct_answer=direct,
        grounded_facts=fact_sections,
        recommended_steps=steps,
        uncertainty=[copy["uncertainty"]],
        source_notes=[build_source_note(source) for source in selected],
    )
    return (
        draft,
        citations,
        {
            "intent": intent,
            "source_ids": ",".join(source.source_id for source in selected),
            "snapshot_date": "2026-10-25",
        },
    )


def render_kazakhstan_foreigner_service_answer(draft: GroundedAnswerDraft) -> str:
    return render_grounded_answer_markdown(draft)


def _detect_intent(text: str) -> str | None:
    for intent in (
        "bank",
        "eresidency",
        "iin",
        "work",
        "business",
        "study",
        "residence",
        "tourism",
        "treatment",
        "private",
        "catalog",
    ):
        if any(_normalize(term) in text for term in _INTENT_TERMS[intent]):
            return intent
    if any(
        term in text
        for term in (
            "what services does the embassy provide",
            "services for foreigners",
            "услуги консульского отдела",
            "что есть для иностранцев",
            "外国人领事服务",
            "有哪些领事服务",
        )
    ):
        return "catalog"
    return None


def _source_ids_for_intent(intent: str) -> list[str]:
    if intent == "iin":
        return [_SOURCES["iin_2026"], _SOURCES["iin_psc"], _SOURCES["eresidency"]]
    if intent == "bank":
        return [_SOURCES["bank"], _SOURCES["iin_2026"], _SOURCES["eresidency"]]
    if intent == "eresidency":
        return [_SOURCES["eresidency"]]
    if intent == "tourism":
        return [_SOURCES["consular_b10_scope"], _SOURCES["evisa"]]
    if intent == "work":
        return [_SOURCES["consular"], _SOURCES["c3"]]
    if intent == "business":
        return [_SOURCES["consular"], _SOURCES["evisa"], _SOURCES["eresidency"]]
    if intent in {"study", "residence"}:
        return [_SOURCES["consular"]]
    if intent in {"private", "catalog"}:
        return [_SOURCES["consular_b10_scope"], _SOURCES["consular"], _SOURCES["evisa"]]
    if intent == "treatment":
        return [_SOURCES["evisa"]]
    return []


def _normalize(text: str) -> str:
    import re

    return " ".join(re.sub(r"[^\w\u4e00-\u9fff]+", " ", text.casefold().replace("ё", "е")).split())
